// ── helpers ───────────────────────────────────────────────────────────────────
const ingestErrors = new Counter("signalflow_ingest_errors");
const ingestOk     = new Counter("signalflow_ingest_ok");
const ingestDur    = new Trend("signalflow_ingest_duration_ms", true);

let pool = STATIC_POOL;

// Advance the timestamp by the VU iteration index so rows are unique
function makePayload(vu, iter) {
  const base = pool[(vu * 100 + iter) % pool.length];
  const ts   = new Date(Date.parse(base.timestamp) + iter * 1000);
  return Object.assign({}, base, { timestamp: ts.toISOString() });
}

// ── default function (called once per VU iteration) ──────────────────────────
export default function () {
  const payload = makePayload(__VU, __ITER);
  const body    = JSON.stringify(payload);
  const headers = {
    "Content-Type":    "application/json",
    "X-Correlation-Id": `bench-vu${__VU}-iter${__ITER}`,
  };

  const res = http.post(`${BASE_URL}/api/v1/logs`, body, { headers });

  const ok = check(res, {
    "status 200": (r) => r.status === 200,
    "has fingerprint": (r) => {
      try { return JSON.parse(r.body).fingerprint !== undefined; } catch { return false; }
    },
  });

  ingestDur.add(res.timings.duration);
  if (ok) {
    ingestOk.increment();
  } else {
    ingestErrors.increment();
  }

  sleep(0.01); // 10 ms think time — keeps throughput realistic
}

export function handleSummary(data) {
  const ts     = new Date().toISOString().replace(/[:.]/g, "-");
  const fname  = `bench/results/ingest-${ts}.json`;
  return {
    [fname]: JSON.stringify(data, null, 2),
    stdout:  textSummary(data),
  };
}

function textSummary(data) {
  const m   = data.metrics;
  const dur = m["http_req_duration"];
  const rps = m["http_reqs"];
  return [
    "── SignalFlow Ingest Benchmark ──────────────────────",
    `  Total requests : ${rps ? rps.values.count : "n/a"}`,
    `  Duration (wall) : ${data.state.testRunDurationMs / 1000}s`,
    `  Throughput      : ${rps ? (rps.values.count / (data.state.testRunDurationMs / 1000)).toFixed(1) : "n/a"} req/s`,
    `  p50 latency     : ${dur ? dur.values["p(50)"].toFixed(1) : "n/a"} ms`,
    `  p95 latency     : ${dur ? dur.values["p(95)"].toFixed(1) : "n/a"} ms`,
    `  p99 latency     : ${dur ? dur.values["p(99)"].toFixed(1) : "n/a"} ms`,
    "─────────────────────────────────────────────────────",
  ].join("\n");
}
